public class Calculator {

    public long add(long num1, long num2) {
        return num1 + num2;
    }
    public long sub(long num1, long num2) {
        return num1 - num2;
    }
    public long mul(long num1, long num2) {
        return num1 * num2;
    }
    public long div(long num1, long num2) {
        return num1 / num2;
    }
}
